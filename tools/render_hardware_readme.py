"""Generate the README hardware evidence table from the maintained catalog.

Run ``python tools/render_hardware_readme.py --check`` to detect drift, or omit
``--check`` to regenerate it. This never detects devices or promotes evidence.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

START = "<!-- BEGIN GENERATED HARDWARE EVIDENCE -->"
END = "<!-- END GENERATED HARDWARE EVIDENCE -->"
ROOT = Path(__file__).resolve().parents[1]


def _cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ").replace("\r", " ")


def render(matrix: dict[str, Any]) -> str:
    """Render only recorded claims, requiring scoped evidence for execution."""
    targets = matrix["targets"]
    if not isinstance(targets, list) or not targets:
        raise ValueError("The maintained catalog must contain targets")
    rows: list[tuple[int, str, str]] = []
    seen: set[str] = set()
    for target in targets:
        target_id = target["target_id"]
        if not isinstance(target_id, str) or not target_id or target_id in seen:
            raise ValueError("Target IDs must be nonempty and unique")
        seen.add(target_id)
        for flag in ("implemented", "execution_tested", "compile_tested"):
            if not isinstance(target[flag], bool):
                raise ValueError(f"{target_id}: {flag} must be a boolean")
        if target["execution_tested"]:
            for key in ("validation_date", "validation_technique", "test_evidence"):
                if not isinstance(target.get(key), str) or not target[key].strip():
                    raise ValueError(f"{target_id}: execution evidence requires {key}")
            rank = 0
            tier = "✅ Recorded hardware execution"
            technique = f"{target['validation_date']}: {target['validation_technique']}"
        elif target["compile_tested"]:
            rank = 1
            tier = "🔬 Compile-time checks"
            technique = target.get(
                "validation_technique", "Compilation recorded; execution pending"
            )
        elif target["implemented"]:
            rank = 2
            tier = "🛠 Implemented; awaiting hardware validation"
            technique = "Help us validate with the matching runtime and device"
        else:
            rank = 3
            tier = "🚧 Integration incomplete"
            technique = target.get("unavailable_reason", "Executable adapter pending")
        cells = (f"`{target_id}`", target["display_name"], tier, technique)
        rows.append((rank, target_id, "| " + " | ".join(_cell(cell) for cell in cells) + " |"))
    return "\n".join(
        [
            START,
            "<!-- Generated by tools/render_hardware_readme.py; "
            "edit hardware_validation_matrix.json. -->",
            "| Target | Hardware | Evidence tier | Technique and scope |",
            "|---|---|---|---|",
            *(row for _, _, row in sorted(rows)),
            END,
        ]
    )


def replace_table(readme: str, generated: str) -> str:
    """Replace exactly one marked region; refuse ambiguous or missing markers."""
    if readme.count(START) != 1 or readme.count(END) != 1:
        raise ValueError("README must contain exactly one hardware evidence marker pair")
    start, end = readme.index(START), readme.index(END)
    if end <= start:
        raise ValueError("Hardware evidence markers are out of order")
    return readme[:start] + generated + readme[end + len(END) :]


def main(argv: list[str] | None = None) -> int:
    """Regenerate the table, or return nonzero when a read-only check finds drift."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--matrix", type=Path, default=ROOT / "hardware_validation_matrix.json")
    parser.add_argument("--readme", type=Path, default=ROOT / "README.md")
    args = parser.parse_args(argv)
    original = args.readme.read_text(encoding="utf-8")
    updated = replace_table(original, render(json.loads(args.matrix.read_text(encoding="utf-8"))))
    if args.check:
        if original != updated:
            print("Hardware table differs; run python tools/render_hardware_readme.py")
            return 1
        return 0
    args.readme.write_text(updated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
