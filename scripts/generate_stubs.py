"""Generate public re-exports from the real package API without importing it.

The implementation modules contain the typed signatures. Re-exporting those
classes prevents this stub from inventing methods or stale constructor options.
"""

from __future__ import annotations

import argparse
import ast
from pathlib import Path


def render_public_stub(source: str) -> str:
    """Resolve each explicit public export to its defining implementation module."""
    tree = ast.parse(source)
    imports = {
        name.asname or name.name: (node.module, name.name)
        for node in tree.body
        if isinstance(node, ast.ImportFrom) and node.module != "__future__"
        for name in node.names
    }
    exports = next(
        ast.literal_eval(node.value)
        for node in tree.body
        if isinstance(node, ast.Assign)
        and any(isinstance(target, ast.Name) and target.id == "__all__" for target in node.targets)
    )
    lines = [
        '"""Public API re-exports; generated by scripts/generate_stubs.py."""',
        "",
        "from __future__ import annotations",
        "",
    ]
    for name in exports:
        if name == "__version__":
            lines.append("__version__: str")
        else:
            module, symbol = imports[name]
            lines.append(f"from {module} import {symbol} as {name}")
    return "\n".join(lines) + "\n"


def main() -> int:
    """Write the generated stub, or verify it without changing files."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    package = Path(__file__).resolve().parents[1] / "src" / "aether"
    destination = package / "__init__.pyi"
    expected = render_public_stub((package / "__init__.py").read_text(encoding="utf-8"))
    if arguments.check:
        if destination.read_text(encoding="utf-8") != expected:
            print("Public API stub is stale; run python scripts/generate_stubs.py")
            return 1
        print("Public API stub matches the implementation exports")
        return 0
    destination.write_text(expected, encoding="utf-8")
    print(f"Generated {destination}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
